function normalise(value) {
  return String(value || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/[''`´]/g, "")
    .replace(/[^a-z0-9]+/g, " ")
    .trim()
    .replace(/\s+/g, " ");
}

const INDEXES = {};
for (const [leagueId, aliases] of Object.entries(ALIASES)) {
  INDEXES[leagueId] = new Map();
  for (const [source, canonical] of Object.entries(aliases)) {
    INDEXES[leagueId].set(normalise(source), canonical);
  }
}

/**
 * Resolve a source team name to the name used by the historical dataset.
 * Returns { name, matched } so callers can log unknown names instead of
 * silently inventing a team.
 */
export function resolveTeam(leagueId, sourceName) {
  const raw = String(sourceName || "").trim();
  if (!raw) return { name: raw, matched: false };

  if (leagueId === "E0" && FPL_NAMES[raw]) {
    return { name: FPL_NAMES[raw], matched: true };
  }

  const index = INDEXES[leagueId];
  if (index) {
    if (index.has(raw)) return { name: index.get(raw), matched: true };
    const key = normalise(raw);
    if (index.has(key)) return { name: index.get(key), matched: true };

    // A few feeds append a suffix ("FC", "AFC", "Calcio") to a name we know.
    const stripped = key
      .replace(/\b(fc|afc|cf|sc|ac|bc|ssc|ss|us|ud|rc|rcd|ca|cd|cs|gd|sv|vfb|vfl|tsg|fsv|bsc|acf|as|ogc|sk|fk|kv|kaa|krc|kvc|rsc)\b/g, " ")
      .replace(/\s+/g, " ")
      .trim();
    if (index.has(stripped)) return { name: index.get(stripped), matched: true };
  }

  return { name: raw, matched: false };
}

export function canonicalTeam(leagueId, sourceName) {
  return resolveTeam(leagueId, sourceName).name;
}

